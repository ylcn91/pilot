func TestDuplicationCollector_DeterministicOrder(t *testing.T) {
	dir := t.TempDir()
	writeDupFile(t, dir, "z.go", dupBlock)
	writeDupFile(t, dir, "m.go", dupBlock)
	writeDupFile(t, dir, "a.go", dupBlock)

	first, err := NewDuplicationCollector().Collect(context.Background(), dir)
	if err != nil {
		t.Fatalf("Collect: %v", err)
	}
	for i := 0; i < 3; i++ {
		again, err := NewDuplicationCollector().Collect(context.Background(), dir)
		if err != nil {
			t.Fatalf("Collect: %v", err)
		}
		if !reflect.DeepEqual(first, again) {
			t.Fatalf("signal order not stable across runs:\nfirst=%+v\nagain=%+v", first, again)
		}
	}
}

func TestNormalizeLine(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string
		ok   bool
	}{
		{"blank", "   ", "", false},
		{"comment", "  // a note", "", false},
		{"collapses_ws", "  a   :=   b  ", "a := b", true},
		{"plain", "x := 1", "x := 1", true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, ok := normalizeLine(tc.in)
			if ok != tc.ok || got != tc.want {
				t.Errorf("normalizeLine(%q) = (%q,%v), want (%q,%v)", tc.in, got, ok, tc.want, tc.ok)
			}
		})
	}
}
