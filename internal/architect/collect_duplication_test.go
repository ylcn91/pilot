// dupBlock is a dupWindowK-line run of distinct significant statements used as a
// reusable copy-paste fixture across the duplication tests.
const dupBlock = `	a := compute(1)
	b := compute(2)
	c := a + b
	d := c * 3
	e := d - 1
	f := e / 2
`

// writeDupFile writes a .go file under dir whose body contains the given block
// inside a function, so the block's lines are significant (non-blank,
// non-comment) and form at least one duplication window.
func writeDupFile(t *testing.T, dir, name, block string) string {
	t.Helper()
	full := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	var sb strings.Builder
	sb.WriteString("package x\n\nfunc run() {\n")
	sb.WriteString(block)
	sb.WriteString("}\n")
	if err := os.WriteFile(full, []byte(sb.String()), 0o644); err != nil {
		t.Fatalf("write: %v", err)
	}
	return full
}

func TestDuplicationCollector_FlagsDuplicatedBlock(t *testing.T) {
	dir := t.TempDir()
	writeDupFile(t, dir, "first.go", dupBlock)
	writeDupFile(t, dir, "second.go", dupBlock)

	signals, err := NewDuplicationCollector().Collect(context.Background(), dir)
	if err != nil {
		t.Fatalf("Collect: %v", err)
	}
	if len(signals) == 0 {
		t.Fatalf("expected at least one duplicate_block signal, got none")
	}
	s := signals[0]
	if s.Kind != kindDuplicateBlock {
		t.Errorf("Kind = %q, want %q", s.Kind, kindDuplicateBlock)
	}
	if s.File == "" {
		t.Errorf("File should be set, got empty")
	}
	if s.Weight <= 0 {
		t.Errorf("Weight = %v, want > 0", s.Weight)
	}
	if s.Risk != pilotapi.RiskMedium {
		t.Errorf("Risk = %q, want medium for a single duplicate across two files", s.Risk)
	}
}

func TestDuplicationCollector_HighRiskForThreeCopies(t *testing.T) {
	dir := t.TempDir()
	writeDupFile(t, dir, "a.go", dupBlock)
	writeDupFile(t, dir, "b.go", dupBlock)
	writeDupFile(t, dir, "c.go", dupBlock)

	signals, err := NewDuplicationCollector().Collect(context.Background(), dir)
	if err != nil {
		t.Fatalf("Collect: %v", err)
	}
	if len(signals) == 0 {
		t.Fatalf("expected a duplicate_block signal for three copies, got none")
	}
	if signals[0].Risk != pilotapi.RiskHigh {
		t.Errorf("Risk = %q, want high for three copies", signals[0].Risk)
	}
	if signals[0].Weight < 3 {
		t.Errorf("Weight = %v, want >= 3 for three copies", signals[0].Weight)
	}
}

